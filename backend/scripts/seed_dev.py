def _model_by_table() -> Dict[str, Any]:
    import app.models  # noqa: F401
    from app.db.base import Base

    return {mapper.class_.__tablename__: mapper.class_ for mapper in Base.registry.mappers}


def reset(session, *, verbose: bool = True) -> Dict[str, int]:
    """Delete every row this script creates, in foreign-key order."""
    from sqlalchemy import delete

    models = _model_by_table()
    deleted: Dict[str, int] = {}
    for table in DELETE_ORDER:
        model = models[table]
        result = session.execute(delete(model))
        deleted[table] = result.rowcount or 0
        if verbose and deleted[table]:
            print(f"  - {table}: {deleted[table]} row(s)")
    session.commit()
    if verbose:
        print(f"reset removed {sum(deleted.values())} row(s)")
    return deleted


def count_rows(session) -> Dict[str, int]:
    from sqlalchemy import func, select

    models = _model_by_table()
    return {
        table: session.execute(select(func.count()).select_from(models[table])).scalar_one()
        for table in PLAN
    }


