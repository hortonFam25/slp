def _school_year_start(today: date) -> date:
    """1 September of the current school year."""
    return date(today.year if today.month >= 9 else today.year - 1, 9, 1)


def _weekday_at(anchor: date, offset_days: int, hour: int, minute: int) -> datetime:
    """A datetime *offset_days* from *anchor*, nudged off Saturday/Sunday."""
    day = anchor + timedelta(days=offset_days)
    while day.weekday() >= 5:
        day += timedelta(days=1)
    return datetime.combine(day, time(hour=hour, minute=minute))


def _progress_note(first: str, last: str, category: str, objective: str, rng: random.Random) -> str:
    """A note that reads like one, with the student's name inside sentences."""
    accuracy = rng.randrange(55, 96)
    trials = rng.choice((10, 15, 20, 25))
    correct = max(1, round(trials * accuracy / 100))
    prompt = rng.choice(PROMPT_LEVELS)
    engagement = rng.choice(ENGAGEMENT)
    return (
        f"{first} worked on {category.lower()} targets this session and was {engagement} throughout. "
        f"Across {trials} structured trials {first} was accurate on {correct} ({accuracy}%) while "
        f"working to {objective}. {first} needed a {prompt} on the harder items, and by the end of "
        f"the session {first} {last[0]}. was self-correcting without clinician support on the easier "
        f"set. Plan: continue at this level next session and probe carryover into conversation."
    )


