    session.flush()
    counts["therapy_sessions"] = len(sessions)

    # -- 11. session goals / objectives / progress entries ------------------
    session_goals: List[SessionGoal] = []
    session_objectives: List[SessionObjective] = []
    progress_entries: List[ObjectiveProgressEntry] = []

    students_by_id = {s.id: s for s in students}
    category_names = {c.id: c.name for c in goal_categories}

    for therapy in sessions:
        student = students_by_id[therapy.student_id]
