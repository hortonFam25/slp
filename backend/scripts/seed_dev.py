_SQLITE_SHIM_INSTALLED = False


def _install_sqlite_shim() -> None:
    """Turn foreign-key enforcement on for sqlite connections.

    This used to also rewrite ``GETDATE()`` to ``CURRENT_TIMESTAMP`` in outgoing
    DDL, because the models hard-coded the SQL-Server-only
    ``server_default=text("GETDATE()")``. They now use ``func.now()``, which the
    sqlite dialect renders as ``CURRENT_TIMESTAMP`` on its own, so only the
    pragma is left.
    """
    global _SQLITE_SHIM_INSTALLED
    if _SQLITE_SHIM_INSTALLED:
        return

    from sqlalchemy import event
    from sqlalchemy.engine import Engine

    @event.listens_for(Engine, "connect")
    def _fk_pragma(dbapi_connection, connection_record):  # noqa: ANN001
        # Foreign keys are OFF by default in sqlite. Turning them on is what
        # makes the local run a real test of the insert/delete ordering.
        try:
            cursor = dbapi_connection.cursor()
            cursor.execute("PRAGMA foreign_keys=ON")
            cursor.close()
        except Exception:  # pragma: no cover - not a sqlite connection
            pass

    _SQLITE_SHIM_INSTALLED = True


def build_sqlite_engine(path: str):
    from sqlalchemy import create_engine

    _install_sqlite_shim()
    if path in (":memory:", "memory"):
        url = "sqlite://"
    else:
        url = f"sqlite:///{Path(path).resolve().as_posix()}"
    return create_engine(url, future=True)


def build_azure_engine(server: str, database: str, driver: str, auth: str):
    """Entra-token connection to Azure SQL, identical to provision_dev_db.py."""
    import provision_dev_db as provision

    return provision.build_engine(server, database, driver=driver, auth=auth)


def _resolve_engine(args: argparse.Namespace):
    if args.sqlite:
        return build_sqlite_engine(args.sqlite)

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    server = args.server or os.environ.get("SLP_DB_SERVER") or "hortonfam.database.windows.net"
    database = args.database or os.environ.get("SLP_DB_NAME") or ""
    if not database:
        raise SystemExit(
            "SLP_DB_NAME (or --database, or --sqlite PATH) is required -- "
            "refusing to guess a database name."
        )
    if database != ALLOWED_DB_NAME:
        raise GuardViolation(
            f"this script only ever seeds {ALLOWED_DB_NAME!r}; SLP_DB_NAME is {database!r}."
        )
    return build_azure_engine(server, database, args.driver, args.auth)


