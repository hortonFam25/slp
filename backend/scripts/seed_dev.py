def assert_seedable(connection) -> str:
    """Return a description of the target, or raise.

    Takes a live connection rather than a URL on purpose: the SQL Server branch
    asks the server which database it actually landed in. A typo in
    ``SLP_DB_NAME``, a stale environment variable, or a connection string that
    resolves somewhere unexpected all fail here rather than after the first
    INSERT.
    """
    dialect = connection.dialect.name

    if dialect == "sqlite":
        return "sqlite"

    if dialect != "mssql":
        raise GuardViolation(
            f"refusing to seed a {dialect!r} database: this script only ever writes to "
            f"sqlite or to the SQL Server database named {ALLOWED_DB_NAME!r}."
        )

    from sqlalchemy import text

    name = connection.execute(text("SELECT DB_NAME()")).scalar_one()
    if name != ALLOWED_DB_NAME:
        raise GuardViolation(
            f"refusing to seed {name!r}. This script writes fake data and only ever "
            f"targets {ALLOWED_DB_NAME!r}. (slpdb_2 is PRODUCTION.)"
        )
    return str(name)


