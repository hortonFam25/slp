"""Fill a development database with believable, entirely fake caseload data.

Nothing in here comes from production. Every name, date of birth, UIC, goal,
objective and progress note is generated by Faker from a fixed seed, so two
runs produce the same caseload and a diff of the seeded data is meaningful.

HARD GUARD
----------
This script writes. It refuses to run unless the target is either

  * a database literally named ``slpdb_dev`` (asked of the SERVER via
    ``SELECT DB_NAME()``, never taken from the caller's argument), or
  * a sqlite file -- the local/test dialect, which by construction cannot be
    one of the Azure databases.

There is no flag, environment variable or argument that turns the guard off.
``slpdb_2`` is production and holds real student PII; it is not a seed target
and never will be.

Usage
-----
    # local scratch database (sqlite)
    python backend/scripts/seed_dev.py --sqlite ./dev-seed.db --reset

    # Azure dev database (Entra token auth via the az CLI)
    SLP_DB_NAME=slpdb_dev python backend/scripts/seed_dev.py --reset

``--reset`` deletes the rows this script created, in foreign-key order, before
re-seeding. Without it, a second run stops rather than colliding with the
unique constraints on ``students.student_alias`` / ``students.uic``.

Only the tables this script seeds are cleared. If some other tool has put rows
into a table that references ``students`` (``progress_tracking``,
``ai_chat_sessions``, ...), ``--reset`` will fail on the foreign key rather
than silently widen its blast radius -- clear those yourself first.
"""

