def run(engine, *, do_reset: bool, verbose: bool = True) -> Dict[str, int]:
    """Guard, ensure the schema exists, optionally reset, then seed."""
    from sqlalchemy.orm import Session

    import app.models  # noqa: F401
    from app.db.base import Base

    with engine.connect() as connection:
        target = assert_seedable(connection)
    if verbose:
        print(f"target: {target} -- guard satisfied")

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        Base.metadata.create_all(engine)

    with Session(engine) as session:
        if do_reset:
            if verbose:
                print("--reset: deleting seeded rows in foreign-key order")
            reset(session, verbose=verbose)
        else:
            existing = count_rows(session)
            populated = {t: n for t, n in existing.items() if n}
            if populated:
                raise SystemExit(
                    "refusing to seed on top of existing rows: "
                    + ", ".join(f"{t}={n}" for t, n in sorted(populated.items()))
                    + "\nRe-run with --reset to clear them first."
                )
        counts = seed(session, verbose=verbose)

    return counts


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="seed_dev.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--sqlite", default=None, help="seed a local sqlite file instead of Azure SQL")
    parser.add_argument("--server", default=None, help="default: $SLP_DB_SERVER")
    parser.add_argument("--database", default=None, help=f"default: $SLP_DB_NAME (must be {ALLOWED_DB_NAME})")
    parser.add_argument(
        "--driver",
        default=os.environ.get("SLP_ODBC_DRIVER", "ODBC Driver 18 for SQL Server"),
        help="ODBC driver name",
    )
    parser.add_argument("--auth", choices=("token", "azcli"), default=os.environ.get("SLP_DB_AUTH", "token"))
    parser.add_argument("--reset", action="store_true", help="delete the seeded rows first (re-runnable)")
    parser.add_argument("--quiet", action="store_true", help="only print the final summary line")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    verbose = not args.quiet
    try:
        engine = _resolve_engine(args)
        counts = run(engine, do_reset=args.reset, verbose=verbose)
    except GuardViolation as exc:
        print(f"GUARD: {exc}", file=sys.stderr)
        return 2
    for table in PLAN:
        got = counts.get(table, 0)
        flag = "" if got == PLAN[table] else f"   (plan says {PLAN[table]})"
        print(f"  {table:<32} {got:>5}{flag}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
